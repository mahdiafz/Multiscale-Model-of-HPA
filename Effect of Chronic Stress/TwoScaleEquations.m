function hpa = TwoScaleEquations(t,x,dax1t,Dax1t,sf1t,Sf1t,stARt,StARt,I_ext)
%% rate constants(k)
Sdax1 = 0.665;
Ssf1 = 0.132;
SstAR = 0.0091; % Up and Down neck % assumed % 0.591
k_dax1= 13.3;
k_Dax1 = 1.04;
k_DAX1 = 0.71;
k_ACORT = 44.5;
k_StARp37 = 0.778;
mu_StARp37 = 19.8;
k_sf1 = 2.64;
k_Sf1 = 0.21;
k_SF1 = 0.73;
k_GR = 1;
k_stAR = 11.8;
k_StAR = 0.06; % Up and Down neck % assumed % 0.93
Gdax1 = 0.015;
GDax1 = 0.00385;
GDAX1 = 0.00193;
mu_ACORT = 0.6931;%0.6931
Gsf1 = 0.0318;
GSf1 = 0.02032;
GSF1 = 0.008;
GpGR = 0.6931;
GstAR = 0.1;
GStAR = 0.00396;
taw_Dax1 = 2.79;
taw_DAX1 = 1.4;
taw_Sf1 = 14.57;
taw_SF1 = 1.38;
taw_StAR = 5.58;
taw_StARp37 = 1;
%% half maximum constants
K_ACTH_dax1 = 90;
K_ACTHlo_Dax1 = 30;
K_ACTHhi_Dax1 = 1000;
K_ACTH_sf1 = 30;
K_ACTH_SF1 = 70;
K_ACTH_stAR = 70;
K_ACTH_StARp37 = 21.62;
K_StARp37 = 40000;
K_ACORT = 4.5;
K_G = 0.76;
K_D = 57000000;
K_Sf1 = 10000;
K_SF1 = 620000;
K_StAR = 10000;
%% Equations
dax1 = x(1);
Dax1 = x(2);
DAX1 = x(3);
sf1 = x(4);
Sf1 = x(5);
SF1 = x(6);
stAR = x(7);
StAR = x(8);
StARp37 = x(9);
ACORT = x(10);
pGR = x(11);
ACTH = x(12);
CRH = x(13);
POMC = x(14);
CORT = x(15);
BEND = x(16);
BLPH = x(17);
BMSH = x(18);
%% A3 constants
KAP = 6e-8;
w = 0.238;
k2 = 8.78e-8; % shift and wide cort and acth % 8.78e-8;
k4 = 2.20e4; % wide acth and CORT
k5 = 240;
k6 = 240;
k23 = 2.4e3;
k24 = 2.4e4;
k19 = 7.2e10; % wide acth and CORT
k20 = 6e8; % wide acth and CORT
k21 = 3.08e3;
k27 = 0.0013;
ke = 0.099;
k_stress = 1;
I_base = 1;
%% Circadian Rhythm
T = 1440;
d1 = 0.3025;
d2 = 2.9;
D = d1 - 0.079145093*d2+ ((0.064 * sin(2*pi*t/T))+0.12*abs(sin(pi*t/T)))*d2;
%% functions
g_m_dax1 = 1/(1+(ACTH*4540e9/K_ACTH_dax1)^4);
g_pm_Dax1 = 1/(1+(ACTH*4540e9/K_ACTHlo_Dax1)) + 1/(1+(K_ACTHhi_Dax1/ACTH*4540e9));
g_p_sf1 = 1/(1+(K_ACTH_sf1/ACTH*4540e9)^4);
g_p_stAR = 1/(1+(K_ACTH_stAR/ACTH*4540e9)^4);
h_Sf1 = 1/(1+K_Sf1/Sf1);
f_ACORT = 1/(1+K_StARp37/StARp37);
f_dax1 = ((SF1/K_SF1)+((SF1*pGR)/(K_SF1*K_G)))/(1+(SF1/K_SF1)+((SF1*pGR)/(K_SF1*K_G)));
g_m_SF1 = 1/(1+ACTH*4540e9/K_ACTH_SF1);
g_m_StARp37 = 1/(1+(ACTH*4540e9/K_ACTH_StARp37)^4);
h_StAR = 1/(1+K_StAR/StAR);
f_pGR = 1/(1+K_ACORT/ACORT);
f_stAR =((SF1/K_SF1))/(1+(SF1/K_SF1)+(DAX1/K_D));
ACORT_STAR = ACORT * ke;
%% ODEs
ddax1 = Sdax1+k_dax1*f_dax1*g_m_dax1-Gdax1*dax1;
dDax1 = k_Dax1*dax1t-GDax1*Dax1*g_pm_Dax1;
dDAX1 = k_DAX1*Dax1t-GDAX1*DAX1;
dsf1 = Ssf1 + k_sf1*g_p_sf1-Gsf1*sf1;
dSf1 = k_Sf1*sf1t-GSf1*h_Sf1;
dSF1 = k_SF1*Sf1t-GSF1*SF1*g_m_SF1;
dstAR = SstAR + k_stAR*f_stAR*g_p_stAR-GstAR*stAR;
dStAR = k_StAR*stARt-GStAR*h_StAR;
dStARp37 = k_StARp37*StARt-mu_StARp37*StARp37*g_m_StARp37;
dACORT = (k_ACORT*f_ACORT-mu_ACORT*ACORT);
dpGR = k_GR*f_pGR-GpGR*pGR;
dACTH = k5*POMC - (k20*CORT + k21)*ACTH;
dCRH = k2*D*k_stress*(I_base+I_ext) - (k4+k19*CORT+k27)*CRH;
dPOMC = k4*CRH - k5*POMC;
dCORT = KAP*(ACORT_STAR-CORT) - w*CORT;
dBEND = k6*BLPH-k23*BEND;
dBLPH = k5*POMC-k6*BLPH;
dBMSH = k6*BLPH-k24*BMSH;
hpa = [ddax1;dDax1;dDAX1;dsf1;dSf1;dSF1;dstAR;dStAR;dStARp37;dACORT;dpGR;dACTH;dCRH;dPOMC;dCORT;dBEND;dBLPH;dBMSH];